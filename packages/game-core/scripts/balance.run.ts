import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { it } from 'vitest';
import '../src/modifiers/index';
import { modifierRegistry } from '../src/modifiers/registry';
import { formatBalanceReport, runCardBalance, type BalanceBot, type BalanceOptions } from '../src/balance/harness';

/**
 * Bot-vs-bot balance run. Settings come from the environment:
 * BALANCE_GAMES, BALANCE_PLIES, BALANCE_BOT (pigeon|chick), BALANCE_DEPTH,
 * BALANCE_SEED, BALANCE_CARDS (comma-separated ids). Writes docs/balance-report.md.
 */
it('runs the balance harness', () => {
  const env = process.env;
  const options: BalanceOptions = {
    games: Number(env.BALANCE_GAMES ?? 20),
    maxPlies: Number(env.BALANCE_PLIES ?? 160),
    bot: (env.BALANCE_BOT ?? 'pigeon') as BalanceBot,
    depth: Number(env.BALANCE_DEPTH ?? 1),
    seed: Number(env.BALANCE_SEED ?? 1),
  };
  const all = [...modifierRegistry.getAll()].map(def => def.id).sort();
  const ids = env.BALANCE_CARDS ? env.BALANCE_CARDS.split(',') : all;
  const names = new Map([...modifierRegistry.getAll()].map(def => [def.id, def.name]));
  const results = [runCardBalance(null, options)];
  for (const id of ids) {
    const started = Date.now();
    results.push(runCardBalance(id, options));
    process.stdout.write(`${id} done in ${Math.round((Date.now() - started) / 1000)}s\n`);
  }
  const report = `# Balance report\n\nGenerated by \`pnpm --filter @pigeon-chess/game-core balance\` on ${new Date().toISOString().slice(0, 10)}.\nWin rate is for the side that drafted the card. Shared cards affect both sides, so their rate mostly shows noise. Plain chess is the baseline. A card that matches the baseline row exactly never changed a game: the bot does not use it, or it needs another card. Small samples swing by 10 points or more, so treat flags as leads, not verdicts.\n\n${formatBalanceReport(results, names, options)}\n`;
  writeFileSync(resolve(__dirname, '../../../docs/balance-report.md'), report);
});
